/**
 * 미래가치 3축(교통·도시·산업개발)의 `info` 에 **실제 측정값이 담겼는지** 판정한다.
 *
 * ⚠️ 이 판정이 없으면 "값이 있는데 없다고 말하는" 거짓이 난다. 세션511이 세 축을
 * 키워드 이진(있음/없음)에서 **거리 등급제**로 바꾸면서 `"평택포승BIX 4.7km"` 처럼
 * **값은 있는데 점수는 낮은** 제3의 상태가 생겼는데, 판정 문구표는 점수만 보고 있었다.
 * 그 결과 704곳(정적 JSON 1,646 중 42.8%)이 실제 산업단지·개발지구를 옆에 두고도
 * "산업 호재 없음"·"개발 계획 없음"을 보고 있었다(세션512 실측).
 *
 * `scoreFuture` 는 값이 없을 때만 `"없음"` 을 넣는다(scoreFuture.ts `info: indStr || "없음"`).
 * 따라서 `"없음"` 이 아니면 측정값이 있는 것이다.
 */
const hasDevValue = (info?: string): info is string => !!info && info !== "없음";

/**
 * 혐오시설 `info`("장례식장,고압선,공장")에서 **점수를 깎는 시설만** 센다.
 *
 * ⚠️ 수집기는 감점 0인 카테고리(공장 1,097곳·장례식장 794곳 등)도 이름을 담는다
 * (`brands.ts` `NOXIOUS_NO_PENALTY` 가 그 이유를 적어 뒀다). 그래서 **전체 개수로 세면 안 된다** —
 * 세션512가 그렇게 세어 "감점 시설 여러 곳"을 55곳(87.3%)에 거짓으로 붙였다.
 */
const countPenalty = (info?: string): number =>
  (info ?? "")
    .split(",")
    .map((s) => s.trim())
    .filter((s) => s in NOXIOUS_PENALTY).length;

/**
 * 거래량 `info`(`"의정부시 6개월 1,234건"`)에서 **건수만** 뽑는다.
 *
 * 앞에 붙는 지역 이름은 시·군·구가 섞여 있어(값 보유 1,466곳 중 616곳이 구가 아니다) 고정할 수
 * 없다. 그래서 이름을 건너뛰고 `"…건"` 앞의 숫자만 읽는다. 형식이 어긋나면 `null` —
 * 밴드를 지어내지 않는다.
 */
const parseTradeCount = (info?: string): number | null => {
  const m = /([\d,]+)\s*건/.exec(info ?? "");
  if (!m) return null;
  const n = Number(m[1].replace(/,/g, ""));
  return Number.isFinite(n) ? n : null;
};

