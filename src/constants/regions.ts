// 도시등급별 교통 4항목 가중치 — `scoreLocation.ts` 의 교통 점수 분자·분모에 동시에 들어간다
// (`maxTransport = 25·subwayW + 30·busW + 20·icW + 20·ktxW + 5`). 세션502 이전까지 이 20개 숫자에
// 근거 주석이 한 줄도 없어 "왜 이 값인가" 를 확인하려면 매번 전수 재측정이 필요했다. 실측 박제:
//
// ⚠️ 손님이 보는 교통 점수는 도시등급별로 크게 갈린다 — 서울 80.0 / 광역시 53.9 / 특례시 51.0 /
//   일반시 42.7 (모집단 = apartments_flat 2,043 곳, 세션502). 이 37점 격차의 원인은 **도시등급이
//   아니라 지하철 유무**다: 지하철 있는 단지 평균 67.7 vs 없는 단지 40.1(= 27.6점). 지하철 0점
//   단지가 전체의 39.2%(800곳)이고 제주·세종·전북·충북·전남은 100% 가 지하철 없음이다.
//
// ✅ 그리고 `subwayW` 차등은 **설계대로 그 격차를 완화하고 있다** — 지하철이 없을 때 깎이는 폭이
//   서울 -27.0점(subwayW 1.0) → 일반시 -12.9점(0.4) 으로 줄어든다. "지하철 없는 게 당연한 곳에선
//   덜 감점" 이 실제로 걸려 있다는 뜻이라, 세션502 는 산식을 **손대지 않기로** 했다(사장님 승인).
//   ("지하철 0점이면 천장에 눌린다" 는 가설도 기각 — 이론상 천장 평균 81.5 인데 실제 최고가 74.1 로
//    아무도 천장 근처에 못 간다. 지하철 없는 곳은 버스도 함께 적기 때문이다(지하철↔버스 상관 0.49).)
//
// ⚠️ `D`(군) 는 **영원히 발동하지 않는다**. 아래 `REGIONS` 는 시도 단위로만 tier 를 주고 군은 각
//   시도의 `gus` 목록에 들어가 그 시도 등급을 그대로 받는다(달성군→A, 울주군→A). 즉 군 단위 차등을
//   의도한 설정이지만 매핑 계층이 그걸 지원하지 않는다. `scoreLocation.ts` 의 미지 지역 폴백도 `C` 라
//   `D` 로 새는 경로가 없다. 지우지 않고 남긴 이유 = 군 단위 차등을 되살릴 때의 설계 흔적.
//   (icW 를 왜 더 낮추지 않았는지는 `scoringTiers.ts` 의 IC_DIST_TIERS 주석 참조.)
